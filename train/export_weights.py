#!/usr/bin/env python3
"""Export the trained MLP to src/mlp_weights.h and write a C/PyTorch
reference file tests/data/mlp_ref.csv for tests/test_mlp.c.

The header holds weights, biases, and standardization constants as
static const double arrays (float32 weights printed exactly with %.17g).

Reference file: N samples (1000 random held-out test atoms + 1000 random
slab atoms, weighted toward the interface), columns
  f0..f4 (features, %.17g), l0_64, l1_64 (PyTorch logits in float64),
  l0_32, l1_32 (PyTorch logits of the float32 model), p_crystal_64
"""
import os

import numpy as np
import pandas as pd
import torch

from train import FEATS, MLP

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")


def fmt(a):
    return ", ".join("%.17g" % float(x) for x in np.ravel(a))


def write_header(sd, mean, std, path):
    W1, b1 = sd["net.0.weight"].double().numpy(), sd["net.0.bias"].double().numpy()
    W2, b2 = sd["net.2.weight"].double().numpy(), sd["net.2.bias"].double().numpy()
    W3, b3 = sd["net.4.weight"].double().numpy(), sd["net.4.bias"].double().numpy()
    assert W1.shape == (16, 5) and W2.shape == (16, 16) and W3.shape == (2, 16)
    rows = lambda W: "\n".join("    {%s}," % fmt(r) for r in W)
    txt = """/*
 * mlp_weights.h: generated by train/export_weights.py from train/model.pt.
 * Do not edit by hand.
 *
 * Network: 5 -> 16 -> 16 -> 2, ReLU. Weight layout W[out][in] (PyTorch).
 * Input order: [qbar4, qbar6, q4, q6, coord], standardized as
 *   x = (feat - MLP_MEAN) / MLP_STD
 * Output: logits[0] = liquid, logits[1] = crystal.
 */
#ifndef MLP_WEIGHTS_H
#define MLP_WEIGHTS_H

#define MLP_NIN 5
#define MLP_NH1 16
#define MLP_NH2 16
#define MLP_NOUT 2

static const double MLP_MEAN[MLP_NIN] = {%s};
static const double MLP_STD[MLP_NIN] = {%s};

static const double MLP_W1[MLP_NH1][MLP_NIN] = {
%s
};
static const double MLP_B1[MLP_NH1] = {%s};

static const double MLP_W2[MLP_NH2][MLP_NH1] = {
%s
};
static const double MLP_B2[MLP_NH2] = {%s};

static const double MLP_W3[MLP_NOUT][MLP_NH2] = {
%s
};
static const double MLP_B3[MLP_NOUT] = {%s};

#endif /* MLP_WEIGHTS_H */
""" % (fmt(mean), fmt(std), rows(W1), fmt(b1), rows(W2), fmt(b2), rows(W3), fmt(b3))
    with open(path, "w") as f:
        f.write(txt)


def main():
    ck = torch.load(os.path.join(HERE, "model.pt"), weights_only=False)
    assert ck["features"] == FEATS
    mean, std = np.array(ck["mean"]), np.array(ck["std"])
    write_header(ck["state_dict"], mean, std, os.path.join(ROOT, "src", "mlp_weights.h"))

    m32 = MLP()
    m32.load_state_dict(ck["state_dict"])
    m32.eval()
    m64 = MLP().double()
    m64.load_state_dict({k: v.double() for k, v in ck["state_dict"].items()})
    m64.eval()

    rng = np.random.default_rng(7)
    te = pd.read_csv(os.path.join(HERE, "data", "test.csv"))
    sl = pd.read_csv(os.path.join(HERE, "data", "slab.csv"))
    near = sl[np.abs(sl["dist"]) < 3.0]
    X = np.concatenate([te[FEATS].values[rng.choice(len(te), 1000, replace=False)],
                        near[FEATS].values[rng.choice(len(near), 1000, replace=False)]])
    with torch.no_grad():
        l64 = m64(torch.tensor((X - mean) / std, dtype=torch.float64)).numpy()
        l32 = m32(torch.tensor((X - mean) / std, dtype=torch.float32)).double().numpy()
    p64 = 1.0 / (1.0 + np.exp(l64[:, 0] - l64[:, 1]))
    os.makedirs(os.path.join(ROOT, "tests", "data"), exist_ok=True)
    out = os.path.join(ROOT, "tests", "data", "mlp_ref.csv")
    with open(out, "w") as f:
        f.write("f0,f1,f2,f3,f4,l0_64,l1_64,l0_32,l1_32,p_crystal_64\n")
        for i in range(len(X)):
            f.write(",".join("%.17g" % v for v in list(X[i]) + [l64[i, 0], l64[i, 1], l32[i, 0],
                                                               l32[i, 1], p64[i]]) + "\n")
    print("wrote src/mlp_weights.h and %s (%d samples, %d predicted crystal)"
          % (out, len(X), int((l64[:, 1] > l64[:, 0]).sum())))


if __name__ == "__main__":
    main()
